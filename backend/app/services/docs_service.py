from __future__ import annotations

from app.services import architecture_service, llm_service
from app.services.chunker import guess_language
from app.services.repo_store import RepoRecord

FILE_DOC_PROMPT = """Generate concise Markdown documentation for the file `{path}` from {repo_label}.

Include, only if applicable (skip sections that don't apply rather than forcing them):
- One-paragraph purpose summary
- A table of exported/top-level functions, classes, or components with a one-line description each
- Notable dependencies this file relies on
- A short usage example if the file's purpose makes one obvious (e.g. a utility function or component)

Be specific and grounded in the actual code below -- do not invent functions that aren't present.

```{language}
{code}
```
"""

REPO_DOC_INTRO_PROMPT = """Write the opening sections (Overview + Getting Started) of a project README for \
{repo_label}, in Markdown, based on this architecture summary. Infer install/run instructions only if the \
tech stack makes them unambiguous (e.g. a package.json implies `npm install`); otherwise state that setup \
steps should be confirmed against the repo's own docs. Keep it grounded and specific, not generic boilerplate.

Architecture summary:
{architecture}
"""


async def generate_file_doc(record: RepoRecord, path: str, code: str, model: str | None = None) -> str:
    language = guess_language(path)
    prompt = FILE_DOC_PROMPT.format(
        path=path, repo_label=f"{record.owner}/{record.name}", language=language, code=code[:9000],
    )
    return await llm_service.complete(
        [{"role": "user", "content": prompt}], model=model, temperature=0.15, max_tokens=1200
    )


async def generate_repo_doc(record: RepoRecord, model: str | None = None) -> str:
    if record.docs_cache and record.docs_cache.get("markdown"):
        return record.docs_cache["markdown"]

    arch = await architecture_service.summarize_architecture(record, model=model)
    intro_prompt = REPO_DOC_INTRO_PROMPT.format(
        repo_label=f"{record.owner}/{record.name}", architecture=arch["summary_markdown"]
    )
    intro = await llm_service.complete(
        [{"role": "user", "content": intro_prompt}], model=model, temperature=0.2, max_tokens=900
    )

    stack_line = ", ".join(arch["tech_stack"]) or "Not automatically detected"
    doc = (
        f"# {record.name}\n\n"
        f"> Auto-generated documentation for [{record.owner}/{record.name}]({record.url}) "
        f"(`{record.ref}`), generated by Repo Radar.\n\n"
        f"{intro}\n\n"
        f"## Architecture\n\n{arch['summary_markdown']}\n\n"
        f"## Tech Stack\n\n{stack_line}\n"
    )
    record.docs_cache = {"markdown": doc}
    return doc
