import yaml from "react-syntax-highlighter/dist/esm/languages/prism/yaml";

const REGISTRY = {
  bash, c, cpp, csharp, css, docker, elixir, go, graphql, java, javascript,
  json, jsx, julia, kotlin, markdown, markup, objectivec, php, protobuf,
  python, r, ruby, rust, scss, sql, swift, toml, tsx, typescript, yaml,
  html: markup, vue: markup, svelte: markup, text: markup,
};

for (const [name, lang] of Object.entries(REGISTRY)) {
  PrismLight.registerLanguage(name, lang);
}

export { PrismLight as SyntaxHighlighter };
